import { execFileSync } from "node:child_process";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { URL } from "node:url";
import { codegen } from "@graphql-codegen/core";
import * as operations from "@graphql-codegen/typescript-operations";
import * as typedDocumentNode from "@graphql-codegen/typed-document-node";
import { parse } from "graphql";

const schema = parse(execFileSync(process.execPath, ["dist/src/printSchema.js"], {
  cwd: new URL("../../server/", import.meta.url),
  encoding: "utf8",
}));

const root = new URL("../graphql/", import.meta.url);
const documents = [];
for (const folder of ["queries", "mutations"]) {
  const dir = new URL(folder + "/", root);
  for (const name of (await readdir(dir)).filter((file) => file.endsWith(".graphql")).sort()) {
    const location = new URL(name, dir);
    documents.push({ location: `${folder}/${name}`, document: parse(await readFile(location, "utf8")) });
  }
}

const filename = "graphql.ts";
const generated = await codegen({
  filename,
  schema,
  documents,
  config: { useTypeImports: true, strictScalars: true, scalars: { DateTimeISO: "string" } },
  plugins: [{ operations: {} }, { typedDocumentNode: {} }],
  pluginMap: { operations, typedDocumentNode },
});
await writeFile(new URL("generated/" + filename, root), "// Generated by npm run gen. Do not edit.\n" + generated);
